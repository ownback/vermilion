# private-patterns.sh: writes the list of this machine's private values that must never reach git
# (~/.config/vermilion/private-patterns.txt, mode 0600). The commit guard (.claude/hooks/guard.py) blocks a commit
# whose staged diff contains one of them. Run it once per machine, and again after a new SMBIOS or network card.
#
# Collected: SMBIOS serial, MLB, ROM and UUID (~/.config/vermilion/smbios-*.json), every MAC address of this
# machine (ifconfig, or ip on Linux), the git author e-mail and name, the host name and the login name. Values already
# in the file are kept (a changed git identity must stay protected). Public identities are left out: a GitHub noreply
# address and its login (`<id>+<login>@users.noreply.github.com`), which appear in every branch name and remote URL.
# No value is printed: only their count and the file's path. VERMILION_CONFIG picks another config directory,
# VERMILION_PRIVATE_PATTERNS another output file.
set -eu
CONF=${VERMILION_CONFIG:-$HOME/.config/vermilion}
OUT=${VERMILION_PRIVATE_PATTERNS:-$CONF/private-patterns.txt}
mkdir -p "$CONF" && chmod 700 "$CONF"
umask 077
tmp=$(mktemp)
# The GitHub login in a noreply address is public.
public=$(git config --global user.email 2>/dev/null | sed -n 's/^[0-9]*+\{0,1\}\([^@]*\)@users\.noreply\.github\.com$/\1/p' |
  tr 'A-Z' 'a-z')
{
  echo "# private values of this machine; generated by scripts/dev/private-patterns.sh on $(date '+%F'). Never commit."
  for f in "$CONF"/smbios-*.json; do
    [ -f "$f" ] || continue
    python3 -I -c '
import base64, json, sys
d = json.load(open(sys.argv[1]))
for k in ("SystemSerialNumber", "MLB", "SystemUUID", "ROM"):
    v = str(d.get(k) or "").strip()
    if not v:
        continue
    print(v)
    if k == "ROM":   # stored as hex or base64: also list the other spellings
        h = v.replace(":", "").replace("-", "")
        try:
            raw = bytes.fromhex(h)
        except ValueError:
            try:
                raw = base64.b64decode(v, validate=True)
            except Exception:
                raw = b""
        if raw:
            print(raw.hex()); print(raw.hex().upper()); print(":".join("%02x" % b for b in raw))
            print(base64.b64encode(raw).decode())
' "$f"
  done
  if command -v ifconfig >/dev/null 2>&1; then
    ifconfig -a 2>/dev/null | awk '/ether /{print $2}'
  elif command -v ip >/dev/null 2>&1; then
    ip link 2>/dev/null | awk '/link\/ether/{print $2}'
  fi | grep -v -i -E '^(00:00:00:00:00:00|ff:ff:ff:ff:ff:ff)$' | while read -r mac; do
    echo "$mac"; echo "$mac" | tr -d ':'; echo "$mac" | tr ':' '-'
  done
  git config --global user.email 2>/dev/null || true
  git config --global user.name 2>/dev/null || true
  hostname -s 2>/dev/null || true
  scutil --get ComputerName 2>/dev/null || true
  scutil --get LocalHostName 2>/dev/null || true
  id -un
  [ -f "$OUT" ] && grep -v '^#' "$OUT"
} | awk -v pub="$public" 'length($0) >= 6 && tolower($0) !~ /@users\.noreply\.github\.com$/ &&
    !(pub != "" && tolower($0) == pub) && !seen[tolower($0)]++' > "$tmp"
mv "$tmp" "$OUT" && chmod 600 "$OUT"
echo "wrote $(grep -c -v '^#' "$OUT") private values to $OUT"
