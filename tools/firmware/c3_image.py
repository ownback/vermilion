#!/usr/bin/env python3
"""c3_image.py [--fw FILE] [--out FILE] [--slice FILE]: generate src/vermilion-boot/phx_c3_hash.inc from the user's own copy of
linux-firmware amdgpu/dcn_3_2_0_dmcub.bin (default: $HOME/gpu/fw/navi31/dcn_3_2_0_dmcub.bin, see fetch_firmware.sh).

PhxBringup's cold-boot PHY fix (debug.phxc3, PhxC3Load.h) streams a 0xA000-byte slice of that file to the PHY SRAM. The slice
is AMD microcode under LICENSE.amdgpu (binary redistribution only), so VermilionBoot holds none of it: the generated header
carries only the slice's length, CRC-32 and SHA-256, and the kext takes the bytes at run time from the installed firmware
(the boot daemon writes them to debug.phxc3_image with `phxctl c3image`; the kext checks them against these hashes).
The slice is checked against a pinned sha256 prefix first; any other firmware revision is refused.

--slice FILE also writes the slice itself (a host-test input; never commit it).
"""
import hashlib, os, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
FW = os.path.join(os.path.expanduser('~'), 'gpu', 'fw', 'navi31', 'dcn_3_2_0_dmcub.bin')
INC = os.path.join(ROOT, 'src', 'vermilion-boot', 'phx_c3_hash.inc')
OFF, LEN, SHA = 0xE200, 0xA000, 'd51426610de22c60'   # OFF/LEN also in tools/phxctl/phxctl.c (C3_OFF, C3_LEN)


def arg(name, default):
    a = sys.argv
    return a[a.index(name) + 1] if name in a else default


def main():
    fw, out = arg('--fw', FW), arg('--out', INC)
    b = open(fw, 'rb').read()
    s = b[OFF:OFF + LEN]
    if len(s) != LEN:
        sys.exit('%s: shorter than 0x%x' % (fw, OFF + LEN))
    sha = hashlib.sha256(s).digest()
    if sha.hex()[:16] != SHA:
        sys.exit('%s: slice sha256 %s, expected prefix %s (unsupported firmware revision)' % (fw, sha.hex(), SHA))
    o = ['// phx_c3_hash.inc: GENERATED by tools/firmware/c3_image.py from linux-firmware amdgpu/dcn_3_2_0_dmcub.bin',
         '// (file md5 %s), file offset 0x%X, 0x%X bytes. Hashes of the C3 slice only: no firmware bytes.' % (hashlib.md5(b).hexdigest(), OFF, LEN),
         'static constexpr unsigned kPhxC3ImageWords = %du;' % (LEN // 2),
         'static constexpr uint32_t kPhxC3ImageCrc32 = 0x%08xu;' % (zlib.crc32(s) & 0xffffffff),
         'static const uint8_t kPhxC3HashSha256[32] = {']
    o.append('    ' + ', '.join('0x%02x' % x for x in sha[:16]) + ',')
    o.append('    ' + ', '.join('0x%02x' % x for x in sha[16:]) + ',')
    o.append('};')
    open(out, 'w').write('\n'.join(o) + '\n')
    print('wrote %s' % out)
    sl = arg('--slice', None)
    if sl:
        open(sl, 'wb').write(s)
        print('wrote %s' % sl)


if __name__ == '__main__':
    main()
